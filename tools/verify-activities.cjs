const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.QA_CHROMIUM ? {executablePath:process.env.QA_CHROMIUM} : {})});
  const context = await browser.newContext({viewport:{width:390,height:844},timezoneId:'America/New_York'});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.clock.install({time:new Date('2026-09-08T16:00:00Z')});
  await page.goto('http://127.0.0.1:8765');
  await page.locator('[data-mode=free-activity]').click();
  const name=page.locator('[name=name]');
  await page.locator('[data-activity="跳绳"]').click();
  await page.locator('#activity-submit').click();
  assert.match(await page.locator('#activity-status').innerText(),/已保存/);
  assert.equal(await page.locator('#week-total').innerText(),'1');
  assert.match(await page.locator('#today-completed').innerText(),/0.*\/ 5/s);
  await page.reload();
  assert.match(await page.locator('#activity-today').innerText(),/1 次/);
  await page.locator('[data-mode=plans]').click();
  await page.locator('[data-check]').first().click();
  assert.equal(await page.locator('#week-total').innerText(),'1');
  await page.locator('[data-view=stats]').click();
  await page.locator('[data-date="2026-09-08"]').click();
  assert.match(await page.locator('#selected-day').innerText(),/跳绳/);
  assert.match(await page.locator('#selected-day').innerText(),/坐姿推胸/);
  await page.locator('[data-edit]').click();
  await name.fill('<img src=x onerror=alert(1)> 散步');
  await page.locator('[name=date]').fill('2026-09-07');
  await page.locator('[name=minutes]').fill('20');
  await page.locator('[name=note]').fill('轻松\n坡度 5%');
  await page.locator('#activity-submit').click();
  assert.equal(await page.locator('#week-total').innerText(),'2');
  await page.locator('[data-view=stats]').click();
  assert.equal(await page.locator('#activity-records img').count(),0);
  assert.match(await page.locator('#activity-records').innerText(),/20 分钟/);
  await page.locator('[data-delete]').click();
  assert.equal(await page.locator('#week-total').innerText(),'1');
  await page.locator('[data-view=today]').click();
  await page.locator('[data-mode=plans]').click();
  await page.locator('[data-check]').first().click();
  assert.equal(await page.locator('#week-total').innerText(),'0');
  // Failed writes must not become successful in-memory check-ins.
  await page.evaluate(()=>{window.realSet=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new Error('quota')};});
  await page.locator('[data-mode=free-activity]').click();
  await name.fill('爬坡');
  await page.locator('#activity-submit').click();
  assert.match(await page.locator('#activity-status').innerText(),/保存失败/);
  assert.equal(await name.inputValue(),'爬坡');
  assert.equal(await page.locator('#week-total').innerText(),'0');
  await page.evaluate(()=>Storage.prototype.setItem=window.realSet);
  await page.locator('#activity-submit').click();
  const other = await context.newPage(); await other.goto('http://127.0.0.1:8765');
  assert.match(await other.locator('#activity-today').innerText(),/1 次/);
  await other.locator('[data-mode=free-activity]').click();
  await other.locator('[data-activity="跳绳"]').click(); await other.locator('#activity-submit').click();
  await page.waitForFunction(()=>document.getElementById('activity-today').textContent.includes('2 次'));
  for(const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`overflow ${width}`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('#free-activity').screenshot({path:'test-artifacts/free-activity-mobile.png'});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: free-only/mixed dates, persistence, edit/delete, escaped text, failed storage, cross-tab sync, mobile layouts.');
})().catch(e=>{console.error(e);process.exit(1)});
